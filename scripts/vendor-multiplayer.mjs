import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'dist/vendor/trystero.js');
const { version, license } = JSON.parse(await readFile(resolve(root, 'node_modules/trystero/package.json'), 'utf8'));
await mkdir(dirname(output), { recursive: true });
await writeFile(resolve(root, 'dist/vendor/TRYSTERO-LICENSE'), await readFile(resolve(root, 'node_modules/trystero/LICENSE')));
await build({
  absWorkingDir: root,
  stdin: {
    contents: "export { joinRoom } from 'trystero';",
    resolveDir: root,
    sourcefile: 'trystero-entry.js',
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  outfile: output,
  legalComments: 'eof',
  banner: { js: `// Trystero ${version} (${license}); generated by scripts/vendor-multiplayer.mjs` },
});
console.log(`Vendored Trystero ${version} to ${output}`);
